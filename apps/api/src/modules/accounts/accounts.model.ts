import type { MailFailReason, Role, StudentStatus } from '@sat/shared';
import { Schema, type Types } from 'mongoose';
import {
  baseSchemaOptions,
  versionField,
  workspaceIdField,
  workspaceIndex,
} from '../../common/persistence/base-schema.js';

export const USER_MODEL = 'User';
export const WORKSPACE_MODEL = 'Workspace';

/** Password e-mails a student can get; `Gửi lại` re-sends the kind that failed (AC-18.4). */
export const STUDENT_MAIL_KINDS = ['activation', 'new_password'] as const;
export type StudentMailKind = (typeof STUDENT_MAIL_KINDS)[number];

export interface UserDoc {
  _id: Types.ObjectId;
  workspaceId: Types.ObjectId;
  role: Role;
  displayName: string;
  /** As entered (trimmed, lower-cased); `emailKey` is the unique system-wide key (Q-1, AC-2.2). */
  email: string;
  emailKey: string;
  /** Name + e-mail without Vietnamese diacritics, lower-case (AC-11.3). */
  searchKey: string;
  phone?: string;
  note?: string;
  /** GV: always `active`. HV: AC-11.1 states. */
  status: StudentStatus;
  failReason?: MailFailReason;
  /** `active` or `failed`, restored by "Mở khóa" (AC-12.4). */
  statusBeforeLock?: 'active' | 'failed';
  /** Kind of the last password e-mail (resent by "Gửi lại"). */
  mailKind?: StudentMailKind;
  /** The account e-mail whose result decides the status; older results are ignored. */
  currentMailId?: Types.ObjectId;
  passwordHash?: string;
  /** HV: generated by the system or set by the student (AC-15.5). */
  passwordSource?: 'system' | 'user';
  activatedAt?: Date;
  lastLoginAt?: Date;
  /** Set on students added by an import, so an interrupted confirmation can be undone (AC-10.5). */
  importId?: Types.ObjectId;
  version: number;
  createdAt: Date;
  updatedAt: Date;
}

export const userSchema = new Schema<UserDoc>(
  {
    workspaceId: workspaceIdField,
    role: { type: String, enum: ['GV', 'HV'], required: true, immutable: true },
    displayName: { type: String, required: true, maxlength: 100 },
    email: { type: String, required: true, maxlength: 254 },
    emailKey: { type: String, required: true, maxlength: 254 },
    searchKey: { type: String, required: true },
    phone: { type: String, maxlength: 16 },
    note: { type: String, maxlength: 500 },
    status: {
      type: String,
      enum: ['pending', 'sending', 'active', 'failed', 'locked'],
      required: true,
    },
    failReason: { type: String, enum: ['not_accepted', 'bounced'] },
    statusBeforeLock: { type: String, enum: ['active', 'failed'] },
    mailKind: { type: String, enum: STUDENT_MAIL_KINDS },
    currentMailId: { type: Schema.Types.ObjectId },
    passwordHash: { type: String },
    passwordSource: { type: String, enum: ['system', 'user'] },
    activatedAt: { type: Date },
    lastLoginAt: { type: Date },
    importId: { type: Schema.Types.ObjectId },
    version: versionField,
  },
  { ...baseSchemaOptions, collection: 'users' },
);
// E-mail is unique across every GV and HV of every workspace (Q-1).
userSchema.index({ emailKey: 1 }, { unique: true });
workspaceIndex(userSchema, { role: 1, createdAt: -1, _id: -1 });
workspaceIndex(userSchema, { role: 1, status: 1 });
workspaceIndex(userSchema, { importId: 1 }, { sparse: true });

export interface WorkspaceDoc {
  _id: Types.ObjectId;
  name: string;
  ownerId: Types.ObjectId;
  createdAt: Date;
  updatedAt: Date;
}

/** A workspace is the tenant itself, so it has no `workspaceId` (raw model access, justified in plan 001). */
export const workspaceSchema = new Schema<WorkspaceDoc>(
  {
    name: { type: String, required: true, maxlength: 200 },
    ownerId: { type: Schema.Types.ObjectId, required: true },
  },
  { ...baseSchemaOptions, collection: 'workspaces' },
);
workspaceSchema.index({ ownerId: 1 }, { unique: true });

export const workspaceNameFor = (gvName: string): string => `Workspace của ${gvName}`;

/** Lower-case, Vietnamese diacritics removed (đ → d), for accent-insensitive search (AC-11.3). */
export function foldText(value: string): string {
  return value
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .toLowerCase();
}

export const searchKeyFor = (displayName: string, email: string): string =>
  `${foldText(displayName)} ${email.toLowerCase()}`;
